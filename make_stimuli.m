%% make_stimuli.m
% Pre-generates all audio needed by the online version of Experiment_SiN.m
%
% Why a grid of SNRs?  The sample-word SNR is adaptive, so the browser has to
% pick a pre-made file for whatever SNR the staircase reaches. In the original
% script the sample SNR starts at 40 dB and only ever moves in steps of 9, 6
% or 3 dB, so every reachable value lies on the grid 40 + 3k. We generate each
% word at every grid value between snrMin and snrMax (the online script clamps
% to the same range).
%
% Output (in outDir):
%   T_<word>.wav          target version of each word (SNR = snrTarget)
%   S_<word>_p40.wav ...  sample versions (p = plus, m = minus, e.g. S_cat_m5.wav = -5 dB)
%   volume_check.wav      example sound for the volume-adjustment screen
% Plus WORDS_for_main_ts.txt in the current folder: paste its contents into main.ts

clearvars; close all;

%addpath ./stringdist
%addpath ./mPraat
addpath ./estools
%addpath ./VOCODER

%% Settings (keep in sync with main.ts)
audioDir        = './stimuli/';
outDir          = './online_stimuli/';
snrTarget       = -6;
snrSampleStart  = 40;
snrStep         = 3;     % greatest common divisor of the step sizes 9, 6, 3
snrMin          = -26;   % = SNR_MIN in main.ts (must be 40 + multiple of 3)
snrMax          = 58;    % = SNR_MAX in main.ts (must be 40 + multiple of 3)
targetRms       = 0.05;  % same normalisation as the original script
globalGain      = 1;     % lower this (e.g. 0.5) if clipping is reported below;
                         % it scales every file equally, so relative levels are kept

% Sound used on the volume-check screen. Ideally a word that is NOT one of the
% 180 experimental items (e.g. a practice word). Leave empty to use the first
% stimulus file.
volumeCheckSource = '';

rng(1); % reproducible noise tokens

%% SNR grid
kLo = ceil((snrMin - snrSampleStart)/snrStep);
kHi = floor((snrMax - snrSampleStart)/snrStep);
snrLevels = snrSampleStart + (kLo:kHi)*snrStep;
assert(snrLevels(1)==snrMin && snrLevels(end)==snrMax, ...
    'snrMin and snrMax must be 40 plus a multiple of 3 so they lie on the staircase grid.');
fprintf('Sample SNR levels (%d): %s\n', numel(snrLevels), mat2str(snrLevels));

%% Noise parameters
load('lpc_val.mat','lpc_val');
params = []; params.lpc_val = lpc_val;

if ~exist(outDir,'dir'); mkdir(outDir); end

wavfiles = dir(fullfile(audioDir,'*.wav'));
nW = numel(wavfiles);
fprintf('Found %d words. Will write %d files.\n', nW, nW*(numel(snrLevels)+1)+1);
if nW < 180
    warning('Fewer than 180 words: blocks beyond %d will not run.', floor(nW/30));
end

words = cell(nW,1);
clipInfo = struct('n',0,'worst',0);

%% Generate
for i = 1:nW
    [~,w] = fileparts(wavfiles(i).name);
    if ~isempty(regexp(w,'[^A-Za-z0-9_\-]','once'))
        warning('Word "%s" contains spaces or special characters; consider renaming the source file.', w);
    end
    words{i} = w;

    [x,fs] = audioread(fullfile(audioDir,wavfiles(i).name));

    % Target word (fixed SNR)
    y = es_addNoiseToSpeech(x,snrTarget,fs,params);
    clipInfo = writeStim(fullfile(outDir,['T_' w '.wav']), y, fs, targetRms, globalGain, clipInfo);

    % Sample word at every grid SNR
    for s = snrLevels
        y = es_addNoiseToSpeech(x,s,fs,params);
        clipInfo = writeStim(fullfile(outDir,sprintf('S_%s_%s.wav',w,snrTag(s))), y, fs, targetRms, globalGain, clipInfo);
    end

    fprintf('%3d/%d  %s\n', i, nW, w);
end

%% Volume-check sound
if isempty(volumeCheckSource)
    volumeCheckSource = fullfile(audioDir,wavfiles(1).name);
end
[x,fs] = audioread(volumeCheckSource);
y = es_addNoiseToSpeech(x,snrSampleStart,fs,params);
clipInfo = writeStim(fullfile(outDir,'volume_check.wav'), y, fs, targetRms, globalGain, clipInfo);

%% Word list for main.ts
fid = fopen('WORDS_for_main_ts.txt','w');
fprintf(fid,'var WORDS: string[] = [\n');
for i = 1:nW
    sep = ','; if i==nW; sep = ''; end
    fprintf(fid,'    ''%s''%s\n', strrep(words{i},'''','\'''), sep);
end
fprintf(fid,'];\n');
fclose(fid);

%% Word list for the jsPsych version (words.js)
fid = fopen('words.js','w');
fprintf(fid,'// Generated by make_gorilla_stimuli.m\nvar WORDS = [\n');
for i = 1:nW
    sep = ','; if i==nW; sep = ''; end
    fprintf(fid,'    ''%s''%s\n', strrep(words{i},'''','\'''), sep);
end
fprintf(fid,'];\n');
fclose(fid);

%% Report
fprintf('\nDone. Files are in %s\n', outDir);
if clipInfo.n > 0
    fprintf(['%d file(s) had peaks >= 1 (worst peak %.2f) and were clipped.\n' ...
             'Set globalGain to about %.2f and run again.\n'], ...
             clipInfo.n, clipInfo.worst, 0.95/clipInfo.worst*globalGain);
else
    fprintf('No clipping (largest peak %.2f).\n', clipInfo.worst);
end

%% Local functions
function clipInfo = writeStim(fn, y, fs, targetRms, globalGain, clipInfo)
    y = y * (targetRms/rms(y(:))) * globalGain;
    pk = max(abs(y(:)));
    clipInfo.worst = max(clipInfo.worst, pk);
    if pk >= 1
        clipInfo.n = clipInfo.n + 1;
        y = max(min(y,0.9999),-0.9999);
    end
    audiowrite(fn, y, fs, 'BitsPerSample', 16); % mono is fine: browsers play it to both ears
end

function t = snrTag(s)
    if s < 0
        t = sprintf('m%d', -s);
    else
        t = sprintf('p%d', s);
    end
end
